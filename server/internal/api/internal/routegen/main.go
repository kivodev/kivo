// Command routegen writes the api package's route table from the OpenAPI
// spec: each operation's mux pattern, operationId, x-kivo-access,
// x-kivo-receiver and x-kivo-upload. An operation without an operationId or
// a known access level stops generation, so it can never be served.
//
// It runs from go generate in internal/api:
//
//	go run ./internal/routegen -spec openapi.yaml -out routes_gen.go
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

// levels are the api package's access levels. Each is written as the name
// of its constant there, so a level missing from that package doesn't
// compile.
var levels = []string{"public", "signedIn", "viewer", "cast", "admin", "play"}

// methods are the keys of a path item that are operations.
var methods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

var errSpec = errors.New("spec")

// route is one operation of the spec and the policy it states.
type route struct {
	method, path, op, level string
	receiver, upload        bool
}

func (r route) pattern() string { return r.method + " " + r.path }

// operation is what routegen reads of one operation of the spec.
type operation struct {
	ID       string `yaml:"operationId"`
	Access   string `yaml:"x-kivo-access"`
	Receiver bool   `yaml:"x-kivo-receiver"`
	Upload   bool   `yaml:"x-kivo-upload"`
}

func main() {
	spec := flag.String("spec", "openapi.yaml", "the OpenAPI spec to read")
	out := flag.String("out", "routes_gen.go", "the Go file to write")
	flag.Parse()
	b, err := os.ReadFile(*spec)
	if err != nil {
		log.Fatal(err)
	}
	rs, err := readRoutes(b)
	if err != nil {
		log.Fatal(err)
	}
	src, err := render(rs)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// readRoutes reads every operation of the spec, sorted by mux pattern. A
// cast route is always a receiver route.
func readRoutes(b []byte) ([]route, error) {
	var doc struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return nil, fmt.Errorf("read the API spec: %w", err)
	}
	var out []route
	var errs []error
	for _, path := range slices.Sorted(maps.Keys(doc.Paths)) {
		item := doc.Paths[path]
		for _, method := range methods {
			node, ok := item[method]
			if !ok {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return nil, fmt.Errorf("read the API spec's %s %s: %w", strings.ToUpper(method), path, err)
			}
			r := route{method: strings.ToUpper(method), path: path, op: op.ID, level: op.Access,
				receiver: op.Receiver || op.Access == "cast", upload: op.Upload}
			if err := check(r); err != nil {
				errs = append(errs, err)
				continue
			}
			out = append(out, r)
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	slices.SortFunc(out, func(a, b route) int { return strings.Compare(a.pattern(), b.pattern()) })
	return out, nil
}

// check reports an operation that has no operationId or no known level.
func check(r route) error {
	switch {
	case r.op == "":
		return fmt.Errorf("%w: %s has no operationId", errSpec, r.pattern())
	case r.level == "":
		return fmt.Errorf("%w: operation %s (%s) has no x-kivo-access", errSpec, r.op, r.pattern())
	case !slices.Contains(levels, r.level):
		return fmt.Errorf("%w: operation %s (%s) has unknown x-kivo-access %q", errSpec, r.op, r.pattern(), r.level)
	}
	return nil
}

// render writes the route table as gofmt'ed Go.
func render(rs []route) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by routegen from openapi.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package api\n\n")
	b.WriteString("// specRoutes are the spec's operations, keyed by mux pattern.\n")
	b.WriteString("var specRoutes = map[string]route{\n")
	for _, r := range rs {
		fmt.Fprintf(&b, "\t%q: {method: %q, path: %q, op: %q, level: %s", r.pattern(), r.method, r.path, r.op, r.level)
		if r.receiver {
			b.WriteString(", receiver: true")
		}
		if r.upload {
			b.WriteString(", upload: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
